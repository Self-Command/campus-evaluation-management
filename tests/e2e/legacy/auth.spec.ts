import { test, expect } from "@playwright/test";
import "dotenv/config";
import { randomBytes } from "node:crypto";
import { hash } from "bcryptjs";
import { db } from "../../../src/server/db";
const prefix = `e2e-${randomBytes(5).toString("hex")}`;
const accounts = (["ADMIN", "PUBLISHER", "STUDENT"] as const).map(role => ({ role, login: `${prefix}-${role}`, password: `Test!${randomBytes(12).toString("hex")}` }));
test.beforeAll(async () => {
  const url = new URL(process.env.DATABASE_URL!);
  if (url.hostname !== "127.0.0.1" || !url.pathname.endsWith("_dev")) throw new Error("浏览器用例仅允许本地开发数据库中的临时测试账号");
  for (const account of accounts) await db.user.create({ data: { login: account.login, name: "自动化测试", role: account.role, passwordHash: await hash(account.password, 12), mustChangePassword: false } });
});
test.afterAll(async () => { await db.user.deleteMany({ where: { login: { startsWith: prefix } } }); await db.$disconnect(); });
test("未登录访问工作台跳转登录", async ({ page }) => {
  await page.goto("/workspace"); await expect(page).toHaveURL(/\/login/);
  await expect(page.getByRole("heading", { name: "欢迎回来" })).toBeVisible();
});
for (const account of accounts) test(`${account.role} 真实登录、角色视图与退出撤销`, async ({ page, browser }) => {
  await page.goto("/login");
  await page.getByLabel("账号", { exact: true }).fill(account.login);
  await page.getByLabel("密码", { exact: true }).fill(account.password);
  await page.getByRole("button", { name: "登录工作空间" }).click();
  await expect(page).toHaveURL(/\/workspace/, { timeout: 30_000 });
  const role = { ADMIN: "管理员", PUBLISHER: "活动发布者", STUDENT: "学生" }[account.role];
  await expect(page.getByText(`${role}视图`, { exact: true })).toBeVisible();
  const permission = await page.request.get("/api/admin/session");
  expect(permission.status()).toBe(account.role === "ADMIN" ? 200 : 403);
  const state = await page.context().storageState();
  await page.screenshot({ path: `.local/${account.role.toLowerCase()}-workspace.png`, fullPage: true });
  await page.getByRole("button", { name: "退出登录" }).click();
  await expect(page).toHaveURL(/\/login/);
  const replay = await browser.newContext({ storageState: state });
  const replayPage = await replay.newPage();
  await replayPage.goto(`${process.env.E2E_BASE_URL ?? "http://localhost:3000"}/workspace`);
  await expect(replayPage).toHaveURL(/\/login/);
  await replay.close();
});
test("首次改密阻止越过页面，改密后所有旧会话失效", async ({ page, browser }) => {
  const account = { login: `${prefix}-first`, password: `First!${randomBytes(10).toString("hex")}` };
  await db.user.create({ data: { login: account.login, name: "首次改密测试", role: "ADMIN", passwordHash: await hash(account.password, 12), mustChangePassword: true } });
  await page.goto("/login");
  await page.getByLabel("账号", { exact: true }).fill(account.login);
  await page.getByLabel("密码", { exact: true }).fill(account.password);
  await page.getByRole("button", { name: "登录工作空间" }).click();
  await expect(page).toHaveURL(/\/change-password/);
  expect((await page.request.get("/api/admin/session")).status()).toBe(403);
  await page.goto("/workspace"); await expect(page).toHaveURL(/\/change-password/);
  const state = await page.context().storageState();
  const newPassword = `Changed!${randomBytes(10).toString("hex")}`;
  await page.getByLabel("当前密码", { exact: true }).fill(account.password);
  await page.getByLabel("新密码", { exact: true }).fill(newPassword);
  await page.getByLabel("确认新密码", { exact: true }).fill(newPassword);
  await page.getByRole("button", { name: "更新密码并重新登录" }).click();
  await expect(page).toHaveURL(/\/login\?changed=1/);
  const replay = await browser.newContext({ storageState: state });
  const replayPage = await replay.newPage();
  await replayPage.goto(`${process.env.E2E_BASE_URL ?? "http://localhost:3000"}/workspace`);
  await expect(replayPage).toHaveURL(/\/login/); await replay.close();
  await page.getByLabel("账号", { exact: true }).fill(account.login);
  await page.getByLabel("密码", { exact: true }).fill(newPassword);
  await page.getByRole("button", { name: "登录工作空间" }).click();
  await expect(page).toHaveURL(/\/workspace/);
});
test("错误密码给出通用反馈与移动端不溢出", async ({ page }) => {
  await page.setViewportSize({ width: 390, height: 844 });
  await page.goto("/login");
  await page.getByLabel("账号", { exact: true }).fill("unknown.test");
  await page.getByLabel("密码", { exact: true }).fill("Wrong-password-123");
  await page.getByRole("button", { name: "登录工作空间" }).click();
  await expect(page.getByRole("alert").filter({ hasText: "账号或密码不正确" })).toBeVisible();
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth)).toBe(true);
  await page.screenshot({ path: ".local/login-mobile.png", fullPage: true });
});
