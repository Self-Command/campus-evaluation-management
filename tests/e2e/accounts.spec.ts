import "dotenv/config";
import { test, expect } from "@playwright/test";
import { randomBytes } from "node:crypto";
import { hash } from "bcryptjs";
import { db } from "../../src/server/db";
const prefix = `acct-${randomBytes(5).toString("hex")}`;
const password = `Test!${randomBytes(12).toString("hex")}`;
let studentId: string;
test.beforeAll(async () => {
  const url = new URL(process.env.DATABASE_URL!);
  if (url.hostname !== "127.0.0.1" || !url.pathname.endsWith("_dev")) throw new Error("仅允许开发测试库");
  await db.user.create({ data: { login: `${prefix}-admin`, name: "账户测试管理员", role: "ADMIN", passwordHash: await hash(password, 12), mustChangePassword: false } });
});
test.afterAll(async () => { await db.user.deleteMany({ where: { login: { startsWith: prefix } } }); await db.$disconnect(); });
test("管理员页面建号、档案、受控密码交付、编辑和重置", async ({ page, browser }) => {
  await page.goto("/login");
  await page.getByLabel("账号", { exact: true }).fill(`${prefix}-admin`);
  await page.getByLabel("密码", { exact: true }).fill(password);
  await page.getByRole("button", { name: "登录工作空间" }).click();
  await expect(page).toHaveURL(/\/workspace/);
  await page.goto("/accounts");
  await page.getByRole("button", { name: "新建账号" }).click();
  await page.getByLabel("姓名", { exact: true }).fill("页面测试学生");
  await page.getByLabel("学号", { exact: true }).fill(`${prefix}-00001`);
  await page.getByLabel("学院", { exact: true }).fill("信息学院");
  await page.getByLabel("专业", { exact: true }).fill("计算机科学");
  await page.getByLabel("班级", { exact: true }).fill("计科01班");
  await page.getByRole("button", { name: "创建账号", exact: true }).click();
  await expect(page.getByRole("heading", { name: "安全交付初始密码" })).toBeVisible();
  const initialPassword = await page.locator("code").textContent();
  expect(initialPassword).toBeTruthy();
  await page.getByRole("button", { name: "已保存，关闭" }).click();
  const row = page.getByRole("row").filter({ hasText: `${prefix}-00001` });
  await expect(row).toContainText("信息学院");
  await row.getByRole("button", { name: `编辑${prefix}-00001`, exact: true }).click();
  await page.getByLabel("学院", { exact: true }).fill("工程学院");
  await page.getByLabel("修改原因").fill("更正学生所属学院");
  await page.getByRole("button", { name: "保存修改" }).click();
  await expect(row).toContainText("工程学院");
  studentId = (await db.user.findUniqueOrThrow({ where: { login: `${prefix}-00001` } })).id;
  const context = await browser.newContext();
  const student = await context.newPage();
  await student.goto("http://localhost:3000/login");
  await student.getByLabel("账号", { exact: true }).fill(`${prefix}-00001`);
  await student.getByLabel("密码", { exact: true }).fill(initialPassword!);
  await student.getByRole("button", { name: "登录工作空间" }).click();
  await expect(student).toHaveURL(/\/change-password/);
  const nextPassword = `Changed!${randomBytes(12).toString("hex")}`;
  await student.getByLabel("当前密码", { exact: true }).fill(initialPassword!);
  await student.getByLabel("新密码", { exact: true }).fill(nextPassword);
  await student.getByLabel("确认新密码", { exact: true }).fill(nextPassword);
  await student.getByRole("button", { name: "更新密码并重新登录" }).click();
  await expect(student).toHaveURL(/\/login/);
  await student.getByLabel("账号", { exact: true }).fill(`${prefix}-00001`);
  await student.getByLabel("密码", { exact: true }).fill(nextPassword);
  await student.getByRole("button", { name: "登录工作空间" }).click();
  await expect(student).toHaveURL(/\/workspace/);
  await student.goto("http://localhost:3000/profile");
  await expect(student.getByRole("definition").filter({ hasText: "工程学院" })).toBeVisible();
  expect((await student.request.get(`/api/students/${studentId}`)).status()).toBe(200);
  expect((await student.request.get("/api/students/another-student")).status()).toBe(403);
  expect((await student.request.get("/api/admin/accounts")).status()).toBe(403);
  await row.getByRole("button", { name: `重置${prefix}-00001密码` }).click();
  await page.getByLabel("重置原因").fill("学生请求重置密码");
  await page.getByRole("button", { name: "确认重置" }).click();
  await expect(page.getByRole("heading", { name: "安全交付初始密码" })).toBeVisible();
  await student.reload(); await expect(student).toHaveURL(/\/login/);
  await page.getByRole("button", { name: "已保存，关闭" }).click();
  await page.screenshot({ path: ".local/accounts-page.png", fullPage: true });
  await context.close();
});
