import "dotenv/config";
import { test, expect } from "@playwright/test";
import { randomBytes } from "node:crypto";
import { hash } from "bcryptjs";
import { db } from "../../src/server/db";
const prefix = `term-${randomBytes(5).toString("hex")}`;
const password = `Test!${randomBytes(12).toString("hex")}`;
test.beforeAll(async () => {
  const url = new URL(process.env.DATABASE_URL!);
  if (url.hostname !== "127.0.0.1" || !url.pathname.endsWith("_dev")) throw new Error("仅允许开发测试库");
  await db.user.create({ data: { login: prefix, name: "学期测试管理员", role: "ADMIN", passwordHash: await hash(password, 12), mustChangePassword: false } });
});
test.afterAll(async () => { await db.term.deleteMany({ where: { name: prefix } }); await db.user.deleteMany({ where: { login: prefix } }); await db.$disconnect(); });
test("管理员创建学期、修改树、试算和开启", async ({ page }) => {
  await page.goto("/login");
  await page.getByLabel("账号", { exact: true }).fill(prefix);
  await page.getByLabel("密码", { exact: true }).fill(password);
  await page.getByRole("button", { name: "登录工作空间" }).click();
  await expect(page).toHaveURL(/\/workspace/);
  await page.goto("/terms");
  await page.getByLabel("学期名称").fill(prefix);
  await page.getByRole("button", { name: "创建学期并套用学校模板" }).click();
  await page.getByRole("row").filter({ hasText: prefix }).getByRole("link", { name: "评分配置与试算" }).click();
  await page.getByRole("button", { name: "编辑综合测评成绩", exact: true }).click();
  await page.getByLabel("模块名称", { exact: true }).fill("本期综合成绩");
  await page.getByRole("button", { name: "应用模块修改" }).click();
  await page.getByRole("button", { name: "保存评分方案" }).click();
  await expect(page.getByRole("alert").filter({ hasText: "评分方案已保存" })).toBeVisible();
  await page.getByLabel("学业成绩（必需）", { exact: true }).fill("90");
  await page.getByLabel("体育素质（必需）", { exact: true }).fill("70");
  await page.getByLabel("思想引领活动", { exact: true }).fill("80");
  await page.getByLabel("社会实践", { exact: true }).fill("18");
  await page.getByLabel("基础素养", { exact: true }).fill("24");
  await page.getByLabel("职业素养", { exact: true }).fill("20");
  await page.getByRole("button", { name: "计算并查看明细" }).click();
  await expect(page.getByRole("alert").filter({ hasText: "综合成绩 82.00" })).toBeVisible();
  await page.getByRole("button", { name: "开启学期", exact: true }).click();
  await page.getByRole("button", { name: "确认开启", exact: true }).click();
  await expect(page.getByRole("alert").filter({ hasText: "学期已开启" })).toBeVisible();
  await page.screenshot({ path: ".local/scheme-page.png", fullPage: true });
});
