import { test, expect, type Page } from "@playwright/test";
import "dotenv/config";
import { randomBytes } from "node:crypto";
import { hash } from "bcryptjs";
import { unlink } from "node:fs/promises";
import { resolve } from "node:path";
import { db } from "../../src/server/db";
import { schemeSchema } from "../../src/lib/scoring/types";
const prefix = `activity-e2e-${randomBytes(5).toString("hex")}`;
const password = `Test!${randomBytes(12).toString("hex")}`;
const users: Record<string, string> = {};
let termId: string;
async function login(page: Page, role: string) {
  await page.goto("/login");
  await page.getByLabel("账号", { exact: true }).fill(`${prefix}-${role}`);
  await page.getByLabel("密码", { exact: true }).fill(password);
  await page.getByRole("button", { name: "登录工作空间" }).click();
  await expect(page).toHaveURL(/\/workspace/);
  await page.goto(`/activities?termId=${termId}`);
}
test.beforeAll(async () => {
  const url = new URL(process.env.DATABASE_URL!);
  if (url.hostname !== "127.0.0.1" || !url.pathname.endsWith("_dev")) throw new Error("仅允许本地开发数据库中的临时数据");
  for (const role of ["ADMIN", "PUBLISHER", "STUDENT"] as const) {
    const login = `${prefix}-${role}`;
    const user = await db.user.create({ data: { login, name: role, role, passwordHash: await hash(password, 12), mustChangePassword: false, ...(role === "STUDENT" ? { studentProfile: { create: { studentNumber: login, college: "学院", major: "专业", className: "班级" } } } : {}) } });
    users[role] = user.id;
  }
  termId = (await db.term.create({ data: { name: prefix, phase: "ACTIVE", scheme: schemeSchema.parse({ nodes: [{ id: "total", parentId: null, name: "综合成绩", order: 0, kind: "SUM" }, { id: "service", parentId: "total", name: "社会实践", order: 0, kind: "ACTIVITY" }, { id: "academic", parentId: "total", name: "学业成绩", order: 1, kind: "GRADE" }], deductions: [{ id: "discipline", nodeId: "total", name: "纪律扣分", coefficient: "1" }] }) } })).id;
});
test.afterAll(async () => {
  const sources = await db.recognitionSource.findMany({ where: { participation: { activity: { termId } } }, select: { id: true } });
  await db.evidenceReference.deleteMany({ where: { sourceId: { in: sources.map(s => s.id) } } });
  await db.recognitionSource.deleteMany({ where: { id: { in: sources.map(s => s.id) } } });
  await db.participation.deleteMany({ where: { activity: { termId } } });
  await db.activity.deleteMany({ where: { termId } });
  await db.deductionInput.deleteMany({ where: { termId } });
  await db.gradeInput.deleteMany({ where: { termId } });
  if (termId) await db.term.delete({ where: { id: termId } });
  await db.participationImport.deleteMany({ where: { termId } });
  await db.gradeImport.deleteMany({ where: { termId } });
  const evidence = await db.evidence.findMany({ where: { ownerId: { in: Object.values(users) } } });
  for (const item of evidence) await unlink(resolve(process.env.EVIDENCE_DIR ?? ".local/evidence", item.storageKey));
  await db.evidence.deleteMany({ where: { id: { in: evidence.map(item => item.id) } } });
  await db.user.deleteMany({ where: { id: { in: Object.values(users) } } });
  await db.$disconnect();
});
