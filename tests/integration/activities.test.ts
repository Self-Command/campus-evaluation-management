test("发布者本人活动与管理员分值确认权限", async () => {
  const audience = { colleges: ["学院"], classes: [{ college: "学院", major: "专业", className: "班级" }], studentIds: [identities.student.id, identities.otherStudent.id] };
  const activity = { name: "志愿服务", organizer: "学生组织", content: "社区服务", requirements: "完成服务", startsAt: "2026-10-20T08:00:00.000Z", endsAt: "2026-10-20T12:00:00.000Z", nodeId: "social_practice", points: "3", audience };
  const saved = await saveActivity(identities.publisher.session, termId, { activity }); activityId = saved.id;
  await expect(saveActivity(identities.otherPublisher.session, termId, { id: saved.id, revision: 0, activity })).rejects.toThrow("本人活动");
  await expect(confirmActivity(identities.publisher.session, termId, { id: saved.id, revision: 0 })).rejects.toThrow("权限");
  expect((await confirmActivity(identities.admin.session, termId, { id: saved.id, revision: 0 })).confirmed).toBe(true);
  const preview = await audienceAction(identities.publisher.session, { action: "preview", termId, audience });
  await publishActivity(identities.publisher.session, termId, { id: saved.id, revision: 1, action: "publish", token: "token" in preview ? preview.token : "" });
  await expect(saveActivity(identities.publisher.session, termId, { id: saved.id, revision: 2, activity: { ...activity, points: "10" } })).rejects.toThrow("统一更正");
});
