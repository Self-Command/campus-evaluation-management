test("成绩缺失与零分、唯一覆盖、防过期和权限校验", async () => {
  const scheme = (await db.term.findUniqueOrThrow({ where: { id: termId } })).scheme as { nodes: { id: string; kind: string }[] };
  const gradeNodes = scheme.nodes.filter(node => node.kind === "GRADE");
  expect(gradeNodes.length).toBeGreaterThan(0);
  const base = { studentLogin: "recognition-student", nodeId: gradeNodes[0].id, value: "0", revision: null, reason: "依据正式成绩单录入" };
  await expect(saveGrade(identities.student.session, termId, base)).rejects.toThrow("权限");
  await expect(saveGrade(identities.admin.session, termId, { ...base, value: "101" })).rejects.toThrow("范围");
  await expect(saveGrade(identities.admin.session, termId, { ...base, nodeId: "social_practice" })).rejects.toThrow("成绩输入");
  for (const node of gradeNodes) await saveGrade(identities.admin.session, termId, { ...base, nodeId: node.id });
  const zero = await getStudentResult(identities.student.session, termId);
  expect(zero.result.complete).toBe(true);
  expect(zero.result.total).not.toBeNull();
  const same = await saveGrade(identities.admin.session, termId, { ...base, revision: 0 });
  expect(same.revision).toBe(0);
  const changed = await saveGrade(identities.admin.session, termId, { ...base, value: "80", revision: 0, reason: "成绩单更正" });
  expect(changed.revision).toBe(1);
  await expect(saveGrade(identities.admin.session, termId, { ...base, value: "70", revision: 0 })).rejects.toThrow("已变化");
  expect(await db.gradeInput.count({ where: { termId, studentId: identities.student.id, nodeId: base.nodeId } })).toBe(1);
});
test("成绩批次错误回滚、同值跳过、覆盖预览、并发幂等及过期数据拒绝", async () => {
  const scheme = (await db.term.findUniqueOrThrow({ where: { id: termId } })).scheme as { nodes: { id: string; kind: string }[] };
  const nodeId = scheme.nodes.find(node => node.kind === "GRADE")!.id;
  const input = { nodeId, rows: [{ login: "recognition-student", value: "90" }, { login: "recognition-otherStudent", value: "101" }], reason: "批量核验成绩" };
  const invalid = await previewGradeImport(identities.admin.session, termId, input);
  expect(invalid.errors).toBe(1);
  await expect(commitGradeImport(identities.admin.session, termId, invalid.id)).rejects.toThrow("错误行");
  const preview = await previewGradeImport(identities.admin.session, termId, { ...input, rows: [{ login: "recognition-student", value: "90" }, { login: "recognition-otherStudent", value: "0" }] });
  expect(preview.rows.map(row => row.state)).toEqual(["OVERWRITE", "NEW"]);
  const results = await Promise.all([commitGradeImport(identities.admin.session, termId, preview.id), commitGradeImport(identities.admin.session, termId, preview.id)]);
  expect(results.filter(result => !result.replay)).toHaveLength(1);
  expect(results[0].written).toBe(2);
  const same = await previewGradeImport(identities.admin.session, termId, { ...input, rows: [{ login: "recognition-student", value: "90.0" }] });
  expect(same.rows[0].state).toBe("SAME");
  expect((await commitGradeImport(identities.admin.session, termId, same.id)).written).toBe(0);
  const stale = await previewGradeImport(identities.admin.session, termId, { ...input, rows: [{ login: "recognition-student", value: "95" }] });
  await saveGrade(identities.admin.session, termId, { studentLogin: "recognition-student", nodeId, value: "91", revision: 2, reason: "手工更正成绩" });
  await expect(commitGradeImport(identities.admin.session, termId, stale.id)).rejects.toThrow("已变化");
});
test("节点扣分只用配置系数、修订防覆盖与理由撤销", async () => {
  const scheme = (await db.term.findUniqueOrThrow({ where: { id: termId } })).scheme as { deductions: { id: string }[] };
  const base = { studentLogin: "recognition-student", projectId: scheme.deductions[0].id, amount: "100", reason: "纪律处理决定", revision: null };
  await expect(saveDeduction(identities.student.session, termId, base)).rejects.toThrow("权限");
  await expect(saveDeduction(identities.admin.session, termId, { ...base, amount: "0" })).rejects.toThrow("正数");
  const before = await getStudentResult(identities.student.session, termId);
  await saveDeduction(identities.admin.session, termId, base);
  const after = await getStudentResult(identities.student.session, termId);
  expect(Number(after.result.total)).toBe(Number(before.result.total) - 100);
  expect(Number(after.result.total)).toBeLessThan(0);
  expect(after.deductions[0].reason).toBe(base.reason);
  await expect(saveDeduction(identities.admin.session, termId, base)).rejects.toThrow("已变化");
  await saveDeduction(identities.admin.session, termId, { ...base, revoked: true, revision: 0, reason: "处理决定撤销" });
  expect((await getStudentResult(identities.student.session, termId)).result.total).toBe(before.result.total);
  expect(await db.deductionInput.count({ where: { termId } })).toBe(1);
});
test("审核修订防并发覆盖，锁定拒绝旧页面审核", async () => {
  await reviewParticipation(identities.admin.session, termId, { id: sourceId, revision: 1, status: "APPROVED", reason: "材料完整" });
  await expect(reviewParticipation(identities.admin.session, termId, { id: sourceId, revision: 0, status: "REJECTED", reason: "旧页面提交" })).rejects.toThrow("已变化");
  await db.term.update({ where: { id: termId }, data: { phase: "LOCKED" } });
  await expect(reviewParticipation(identities.admin.session, termId, { id: sourceId, revision: 1, status: "REJECTED", reason: "锁定后修改" })).rejects.toThrow("阶段");
});
